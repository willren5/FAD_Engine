#pragma once

#include <fad/engine/assets/WavetableBank.h>
#include <algorithm>
#include <cmath>
#include <array>

namespace fadmodel1::dsp
{
// Raw views pin the existing bank reader counts; retirement owns destruction.
// Configure at a block boundary; no ownership allocation occurs on audio.
class NoiseSamplePlayer
{
public:
    ~NoiseSamplePlayer() { releaseAssetViews(); }
    NoiseSamplePlayer() = default;
    NoiseSamplePlayer(const NoiseSamplePlayer&) = delete;
    NoiseSamplePlayer& operator=(const NoiseSamplePlayer&) = delete;

    void releaseAssetViews() noexcept
    {
        releaseOwner(oldOwner);
        releaseOwner(owner);
        asset = oldAsset = nullptr;
        transitionRemaining = 0;
        configured = false;
    }

    bool needsBuiltinSample() const noexcept
    {
        return (asset == nullptr && procedural) || (transitionRemaining > 0 && oldAsset == nullptr && oldProcedural && !holdPrevious);
    }
    bool isTransitioning() const noexcept { return transitionRemaining > 0; }
    bool lastSampleWasTransition() const noexcept { return lastWasTransition; }
    std::array<float, 2> lastAudibleSample(float pcmGain, float builtinGain) const noexcept
    {
        return {lastPcm[0] * pcmGain + lastBuiltin[0] * builtinGain,
                lastPcm[1] * pcmGain + lastBuiltin[1] * builtinGain};
    }

    void reset(double phase = 0.0) noexcept
    {
        releaseOwner(oldOwner);
        oldAsset = nullptr;
        transitionRemaining = 0;
        configured = false;
        startPhase = std::isfinite(phase) ? phase - std::floor(phase) : 0.0;
        position = 0.0;
        pendingReset = true;
        ended = false;
    }

    void configure(const wavetable::WavetableData* next, double outputRate,
                   double rate, bool oneShotIn,
                   const wavetable::RuntimeWavetableBank::PublishedOwnership* nextOwner = nullptr,
                   bool proceduralIn = false) noexcept
    {
        const bool resumeLoop = next == asset && proceduralIn == procedural
            && oneShot && !oneShotIn && ended;
        if (next != asset || proceduralIn != procedural || resumeLoop) {
            const bool interrupted = transitionRemaining > 0;
            releaseOwner(oldOwner);
            oldAsset = interrupted ? nullptr : asset;
            oldProcedural = procedural;
            procedural = proceduralIn;
            oldPosition = position;
            oldStep = step;
            oldOneShot = oneShot;
            oldEnded = ended;
            holdPrevious = interrupted;
            heldSample = lastSample;
            heldPcm = lastPcm;
            heldBuiltin = lastBuiltin;
            if (!interrupted) oldOwner = std::exchange(owner, nullptr);
            else releaseOwner(owner);
            asset = next;
            owner = next != nullptr ? nextOwner : nullptr;
            if (owner != nullptr) owner->audioReaderCount.fetch_add(1, std::memory_order_acq_rel);
            if (!resumeLoop) {
                position = 0.0;
                pendingReset = true;
            }
            ended = false;
            const double transitionRate = std::isfinite(outputRate) && outputRate > 0.0
                ? std::min(outputRate, 384000.0) : 48000.0;
            transitionLength = std::max(1, static_cast<int>(std::ceil(transitionRate * 0.005)));
            transitionRemaining = configured ? transitionLength : 0;
            if (!configured) { releaseOwner(oldOwner); oldAsset = nullptr; }
        }
        if (pendingReset) {
            position = asset != nullptr ? std::floor(startPhase * static_cast<double>(asset->sampleLength)) : 0.0;
            pendingReset = false;
        }
        if (asset != nullptr && owner != nextOwner)
        {
            if (nextOwner != nullptr) nextOwner->audioReaderCount.fetch_add(1, std::memory_order_acq_rel);
            releaseOwner(owner);
            owner = nextOwner;
        }
        configured = true;
        oneShot = oneShotIn;
        step = asset != nullptr && asset->sampleLength > 0 && outputRate > 0.0
            ? asset->sampleRate / outputRate * rate : 0.0;
        if (! std::isfinite(step) || step <= 0.0) step = 0.0;
        baseStep=step;
    }

    void setPitchMultiplier(double multiplier) noexcept
    {
        step=std::isfinite(multiplier) && multiplier>0 ? baseStep*multiplier : 0.0;
        if(!std::isfinite(step))step=0.0;
    }

    float nextSample() noexcept { return nextStereoSample()[0]; }

    std::array<float, 2> nextStereoSample() noexcept { return nextStereoSample({}); }

    // Builtin input is generated by the existing RNG only when needed. The
    // same mixed pair is consumed by the audible and modulation paths.
    std::array<float, 2> nextStereoSample(std::array<float, 2> builtin) noexcept
    {
        lastWasTransition = transitionRemaining > 0;
        auto current = asset != nullptr ? readHead(asset, position, step, oneShot, ended) : procedural ? builtin : std::array<float, 2>{};
        lastPcm = asset != nullptr ? current : std::array<float, 2>{};
        lastBuiltin = asset == nullptr && procedural ? current : std::array<float, 2>{};
        if (transitionRemaining > 0)
        {
            auto previous = holdPrevious ? heldSample
                : oldAsset != nullptr ? readHead(oldAsset, oldPosition, oldStep, oldOneShot, oldEnded) : oldProcedural ? builtin : std::array<float, 2>{};
            const float mix = static_cast<float>(transitionLength - transitionRemaining) / static_cast<float>(transitionLength);
            for (size_t i = 0; i < current.size(); ++i)
            {
                current[i] = previous[i] * (1.0f - mix) + current[i] * mix;
                lastPcm[i] = lastPcm[i] * mix + (holdPrevious ? heldPcm[i] : oldAsset != nullptr ? previous[i] : 0.0f) * (1.0f - mix);
                lastBuiltin[i] = lastBuiltin[i] * mix + (holdPrevious ? heldBuiltin[i] : oldAsset == nullptr && oldProcedural ? previous[i] : 0.0f) * (1.0f - mix);
            }
            if (--transitionRemaining == 0) { releaseOwner(oldOwner); oldAsset = nullptr; }
        }
        lastSample = current;
        return current;
    }

    static double playbackRate(float pitch, float fine, bool keytrack, int note,
                               float modulation = 0.0f) noexcept
    {
        const double value = std::isfinite(pitch) ? std::clamp(static_cast<double>(pitch), 0.0, 1.0) : 0.5;
        const double fineOffset = (std::isfinite(fine) ? std::clamp(static_cast<double>(fine), 0.0, 1.0) - 0.5 : 0.0) * 2.0;
        const double offset = std::isfinite(modulation) ? std::clamp(static_cast<double>(modulation), -1.0, 1.0) : 0.0;
        // Native keytracked Pitch quantizes the saved knob, not its modulation.
        // Macro versus direct Pitch+Fine captures are sample-identical for both
        // signs. Without keytracking, modulate the original piecewise knob law.
        const double modulated = std::clamp(value + offset, 0.0, 1.0);
        const double semitones = std::clamp(std::floor((value - 0.5) * 128.0 + 0.5) + offset * 128.0, -64.0, 64.0);
        const double octaves = keytrack ? (semitones + std::clamp(note, 0, 127) - 72.0) / 12.0
            : (modulated - 0.5) * (modulated < 0.5 ? 32.0 : 8.0);
        return std::exp2(octaves + fineOffset * (keytrack ? 1.0 / 12.0 : 0.08));
    }

private:
    static void releaseOwner(const wavetable::RuntimeWavetableBank::PublishedOwnership*& view) noexcept
    {
        if (view != nullptr) view->audioReaderCount.fetch_sub(1, std::memory_order_acq_rel);
        view = nullptr;
    }

    static std::array<float, 2> readHead(const wavetable::WavetableData* asset,
        double& position, double step, bool oneShot, bool& ended) noexcept
    {
        if (asset == nullptr || asset->sampleLength == 0 || step == 0.0 || ended)
            return {};
        const auto length = static_cast<double>(asset->sampleLength);
        if (position >= length) {
            if (oneShot) { ended = true; return {}; }
            position = std::fmod(position, length);
        }
        const auto index = static_cast<int64_t>(position);
        const auto fraction = static_cast<float>(position - static_cast<double>(index));
        const auto read = [asset, oneShot](int64_t at) noexcept {
            const auto count = static_cast<int64_t>(asset->sampleLength);
            if (at < 0 || at >= count)
            {
                if (oneShot) return std::array<float, 2>{};
                at %= count;
                if (at < 0) at += count;
            }
            const auto sample = static_cast<size_t>(at) * static_cast<size_t>(asset->sampleChannels);
            const auto frame = sample / asset->frameSize;
            const auto offset = sample % asset->frameSize;
            const auto left = asset->frames[frame][offset];
            const auto right = asset->sampleChannels == 1 ? left
                : offset + 1 < asset->frameSize ? asset->frames[frame][offset + 1]
                : asset->frames[frame + 1][0];
            return std::array<float, 2>{left, right};
        };
        std::array<float, 2> a, b, c, d;
        const auto stride = static_cast<size_t>(asset->sampleChannels);
        const auto centre = static_cast<size_t>(index) * stride;
        const auto frame = centre / asset->frameSize;
        const auto offset = centre % asset->frameSize;
        if (index > 0 && static_cast<uint64_t>(index) + 2u < asset->sampleLength
            && offset >= stride && offset + 3u * stride <= asset->frameSize)
        {
            // All four taps share a frame. Resolve its address once; retain
            // the original boundary reader for loops, tails and split stereo.
            const auto* samples = asset->frames[frame].data();
            const auto rightOffset = asset->sampleChannels == 1 ? 0u : 1u;
            const auto withinFrame = [&](size_t at) noexcept {
                return std::array<float, 2>{samples[at], samples[at + rightOffset]};
            };
            a = withinFrame(offset - stride);
            b = withinFrame(offset);
            c = withinFrame(offset + stride);
            d = withinFrame(offset + 2u * stride);
        }
        else
        {
            a = read(index - 1); b = read(index);
            c = read(index + 1); d = read(index + 2);
        }
        // Four-point interpolation preserves stored PCM at integer positions.
        // Native Serum's resampling kernel is not claimed to be sample-exact.
        const auto interpolate = [&](size_t channel) noexcept {
            return b[channel] + 0.5f * fraction * (c[channel] - a[channel] + fraction *
                (2.0f * a[channel] - 5.0f * b[channel] + 4.0f * c[channel] - d[channel] + fraction *
                 (3.0f * (b[channel] - c[channel]) + d[channel] - a[channel])));
        };
        const float left = interpolate(0);
        const std::array<float, 2> result {left, asset->sampleChannels == 1 ? left : interpolate(1)};
        position += step;
        return result;
    }

    const wavetable::RuntimeWavetableBank::PublishedOwnership* owner = nullptr;
    const wavetable::RuntimeWavetableBank::PublishedOwnership* oldOwner = nullptr;
    const wavetable::WavetableData* oldAsset = nullptr;
    double oldPosition = 0.0, oldStep = 0.0;
    bool procedural = false, oldProcedural = false, lastWasTransition = false;
    bool oldOneShot = false, oldEnded = false, configured = false, holdPrevious = false;
    int transitionRemaining = 0, transitionLength = 1;
    std::array<float, 2> lastSample{}, heldSample{}, lastPcm{}, lastBuiltin{}, heldPcm{}, heldBuiltin{};
    const wavetable::WavetableData* asset = nullptr;
    double position = 0.0, startPhase = 0.0, step = 0.0, baseStep = 0.0;
    bool oneShot = false, ended = false, pendingReset = false;
};
}
